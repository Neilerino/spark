    // ── Real-world integration test (sqlite3.h) ────────────────────

    #[test]
    #[ignore] // requires sqlite3.h on the system — run with `cargo test -p spark_bindgen -- --ignored`
    fn bindgen_sqlite3_real_header() {
        if !libclang_available() {
            return;
        }

        // Find sqlite3.h via macOS SDK or common paths.
        let sdk_path = std::process::Command::new("xcrun")
            .args(["--show-sdk-path"])
            .output()
            .ok()
            .filter(|o| o.status.success())
            .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string());

        let header_path = if let Some(ref sdk) = sdk_path {
            let p = format!("{sdk}/usr/include/sqlite3.h");
            if std::path::Path::new(&p).exists() {
                p
            } else {
                return;
            }
        } else if std::path::Path::new("/usr/include/sqlite3.h").exists() {
            "/usr/include/sqlite3.h".to_string()
        } else {
            return;
        };

        let mut include_paths = Vec::new();
        let mut extra_args = Vec::new();
        if let Some(ref sdk) = sdk_path {
            include_paths.push(format!("{sdk}/usr/include"));
            extra_args.push(format!("-isysroot{sdk}"));
        }

        let config = BindgenConfig {
            header_path,
            library_name: Some("sqlite3".to_string()),
            include_paths,
            extra_args,
        };

        let result = run_bindgen(&config).expect("run_bindgen on sqlite3.h failed");
        let source = render_spark(&result);

        // sqlite3.h has hundreds of functions.
        assert!(
            result.output.functions.len() > 10,
            "expected many sqlite3 functions, got {}",
            result.output.functions.len()
        );

        // Check well-known functions are present.
        let names: Vec<&str> = result
            .output
            .functions
            .iter()
            .map(|f| f.name.as_str())
            .collect();
        assert!(names.contains(&"sqlite3_open"), "missing sqlite3_open");
        assert!(names.contains(&"sqlite3_close"), "missing sqlite3_close");
        assert!(names.contains(&"sqlite3_errmsg"), "missing sqlite3_errmsg");

        // Verify output structure.
        assert!(source.starts_with("// Generated by spark bindgen from sqlite3.h\n"));
        assert!(source.contains("link \"sqlite3\""));

        // Variadic functions like sqlite3_mprintf should be skipped.
        assert!(!names.contains(&"sqlite3_mprintf"));
        assert!(
            result
                .output
                .warnings
                .iter()
                .any(|w| w.entity == "sqlite3_mprintf")
        );
    }
