    #[test]
    fn typedef_resolved_through_canonical() {
        if !libclang_available() {
            return;
        }

        // size_t is a typedef — should resolve to UInt.
        let output = bindgen_from_source(
            "#include <stddef.h>\nsize_t get_size(size_t n);\n",
        );

        // Find the get_size function (may also pick up things from stddef.h
        // if filename filtering fails, but our filter should exclude those).
        let func = output
            .functions
            .iter()
            .find(|f| f.name == "get_size")
            .expect("get_size not found");

        assert_eq!(func.params[0].1, "UInt");
        assert_eq!(func.return_type, "UInt");
    }

    #[test]
